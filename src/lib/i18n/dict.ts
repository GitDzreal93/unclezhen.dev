// Cookie-based i18n. Two locales, default zh. Translations live here in a
// flat key→string map; the `t()` helper does `{var}` interpolation and
// gracefully falls back to zh (then to the key) if a translation is missing.
//
// Scope: the public site only. Admin is dev-only and stays zh. Pages that
// opt into i18n call t(locale, "key") in their server components and pass
// the resulting strings down to client components as props. Client components
// read locale from the props bag, not from a context, to keep the rendering
// path explicit.

export type Locale = "zh" | "en";
export const DEFAULT_LOCALE: Locale = "zh";
export const SUPPORTED_LOCALES: Locale[] = ["zh", "en"];

export const LOCALE_LABEL: Record<Locale, string> = {
  zh: "中文",
  en: "English",
};

type Vars = Record<string, string | number>;

export function t(locale: Locale | undefined, key: string, vars?: Vars): string {
  const value =
    (locale && DICT[locale]?.[key]) ?? DICT.zh[key] ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`
  );
}

/** Localize code-owned navigation keys while preserving DB labels for custom entries. */
export function navLabel(locale: Locale, key: string, fallback: string): string {
  return DICT[locale]?.[`nav.${key}`] ?? fallback;
}

